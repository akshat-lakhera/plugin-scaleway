package io.kestra.plugin.scaleway.storage;

import java.io.File;
import java.io.InputStream;
import java.net.URI;
import java.nio.file.Files;
import java.nio.file.StandardCopyOption;
import java.util.Map;

import io.kestra.core.models.annotations.Example;
import io.kestra.core.models.annotations.Metric;
import io.kestra.core.models.annotations.Plugin;
import io.kestra.core.models.annotations.PluginProperty;
import io.kestra.core.models.executions.metrics.Counter;
import io.kestra.core.models.property.Property;
import io.kestra.core.models.tasks.RunnableTask;
import io.kestra.core.runners.RunContext;
import io.kestra.core.utils.FileUtils;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotNull;
import lombok.*;
import lombok.experimental.SuperBuilder;
import software.amazon.awssdk.core.sync.RequestBody;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.PutObjectRequest;
import software.amazon.awssdk.services.s3.model.PutObjectResponse;

@SuperBuilder
@ToString
@EqualsAndHashCode
@Getter
@NoArgsConstructor
@Plugin(
    examples = {
        @Example(
            title = "Upload a file generated by a previous task to a Scaleway bucket",
            full = true,
            code = """
                id: export_to_scaleway_storage
                namespace: company.team

                tasks:
                  - id: generate_report
                    type: io.kestra.plugin.scripts.python.Script
                    outputFiles:
                      - report.csv
                    script: |
                      with open('report.csv', 'w') as f:
                          f.write("id,revenue\\n1,1000\\n2,2500\\n")

                  - id: upload_report
                    type: io.kestra.plugin.scaleway.storage.Upload
                    accessKey: "{{ secret('SCW_ACCESS_KEY') }}"
                    secretKey: "{{ secret('SCW_SECRET_KEY') }}"
                    region: fr-par
                    bucket: my-data-lake
                    key: "reports/{{ execution.startDate | dateFormat('yyyy-MM-dd') }}/report.csv"
                    from: "{{ outputs.generate_report.outputFiles['report.csv'] }}"
                """
        ),
        @Example(
            title = "Upload a FILE input with a content type and custom metadata",
            full = true,
            code = """
                id: scaleway_storage_upload
                namespace: company.team

                inputs:
                  - id: file
                    type: FILE

                tasks:
                  - id: upload
                    type: io.kestra.plugin.scaleway.storage.Upload
                    accessKey: "{{ secret('SCW_ACCESS_KEY') }}"
                    secretKey: "{{ secret('SCW_SECRET_KEY') }}"
                    region: nl-ams
                    bucket: my-bucket
                    key: "uploads/data.json"
                    from: "{{ inputs.file }}"
                    contentType: application/json
                    metadata:
                      source: kestra
                """
        )
    },
    metrics = {
        @Metric(
            name = "file.size",
            type = Counter.TYPE,
            unit = "bytes",
            description = "Size of the uploaded file."
        )
    }
)
@Schema(
    title = "Upload a file to Scaleway Object Storage",
    description = "Uploads a file from Kestra internal storage to a Scaleway Object Storage bucket in a single PUT request, which Scaleway limits to 5 GB."
)
public class Upload extends AbstractS3 implements RunnableTask<Upload.Output> {
    @Schema(
        title = "Bucket name",
        description = "Name of the destination bucket."
    )
    @NotNull
    @PluginProperty(group = "main")
    private Property<String> bucket;

    @Schema(
        title = "Object key",
        description = "Full key of the object to create or overwrite in the bucket."
    )
    @NotNull
    @PluginProperty(group = "main")
    private Property<String> key;

    @Schema(
        title = "Source file",
        description = "Kestra internal storage URI of the file to upload, usually an output or a FILE input."
    )
    @NotNull
    @PluginProperty(internalStorageURI = true, group = "main")
    private Property<String> from;

    @Schema(
        title = "Content type",
        description = "MIME type stored with the object, for example text/csv."
    )
    @PluginProperty(group = "advanced")
    private Property<String> contentType;

    @Schema(
        title = "Metadata",
        description = "User-defined key/value metadata stored with the object."
    )
    @PluginProperty(group = "advanced")
    private Property<Map<String, String>> metadata;

    @Schema(
        title = "Storage class",
        description = "Scaleway storage class of the object: STANDARD, ONEZONE_IA or GLACIER. Defaults to the bucket default."
    )
    @PluginProperty(group = "advanced")
    private Property<String> storageClass;

    @Override
    public Output run(RunContext runContext) throws Exception {
        var rBucket = runContext.render(this.bucket).as(String.class).orElseThrow();
        var rKey = runContext.render(this.key).as(String.class).orElseThrow();
        var rFrom = URI.create(runContext.render(this.from).as(String.class).orElseThrow());

        // A file gives the SDK a known content length, which a plain stream does not.
        File tempFile = runContext.workingDir().createTempFile(FileUtils.getExtension(rFrom)).toFile();
        try (InputStream inputStream = runContext.storage().getFile(rFrom)) {
            Files.copy(inputStream, tempFile.toPath(), StandardCopyOption.REPLACE_EXISTING);
        }

        var builder = PutObjectRequest.builder()
            .bucket(rBucket)
            .key(rKey);
        runContext.render(this.contentType).as(String.class).ifPresent(builder::contentType);
        runContext.render(this.storageClass).as(String.class).ifPresent(builder::storageClass);
        Map<String, String> rMetadata = runContext.render(this.metadata).asMap(String.class, String.class);
        if (!rMetadata.isEmpty()) {
            builder.metadata(rMetadata);
        }

        try (S3Client client = this.client(runContext)) {
            runContext.logger().debug("Uploading '{}' to '{}/{}'", rFrom, rBucket, rKey);
            PutObjectResponse response = client.putObject(builder.build(), RequestBody.fromFile(tempFile));

            runContext.metric(Counter.of("file.size", tempFile.length()));

            return Output.builder()
                .bucket(rBucket)
                .key(rKey)
                .eTag(response.eTag())
                .versionId(response.versionId())
                .build();
        }
    }

    @Builder
    @Getter
    public static class Output implements io.kestra.core.models.tasks.Output {
        @Schema(title = "Bucket name")
        private final String bucket;

        @Schema(title = "Object key")
        private final String key;

        @Schema(title = "ETag of the uploaded object")
        private final String eTag;

        @Schema(title = "Version ID of the uploaded object", description = "Only set when versioning is enabled on the bucket.")
        private final String versionId;
    }
}
